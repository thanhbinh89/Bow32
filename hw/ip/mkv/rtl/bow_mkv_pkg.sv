// MKV block cipher (TCVN 14263:2024): the layers of the round function on
// the 256 bit state of the Bow32 MKV core (docs/ip/mkv.md).
//
// Byte b of a block (in the order of the standard) is state[8*b +: 8]. The
// state has four sub-states (columns) x^c of t bytes, column c = bytes
// c*t .. c*t+t-1, byte j of a column = x^c_j, entry j of the MixWords vector:
//   wide = 1  MKV-256, t = 8, columns state[64*c +: 64]
//   wide = 0  MKV-128, t = 4, columns state[32*c +: 32], bits 255:128 = 0
// The layer functions return 0 in bits 255:128 when wide = 0 (except
// sub_cells / inv_sub_cells, which work on every byte).

package bow_mkv_pkg;

  import bow_mkv_tables_pkg::*;

  typedef logic [255:0] state_t;

  // MixWords matrices M4, M4Inv, M8, M8Inv over GF(2^8) / x^8 + x^5 + x^3 + x + 1
  // and the key schedule constants come from bow_mkv_tables_pkg (generated by
  // tools/mkv/mkv_model.py).

  // Product in GF(2^8); with a constant c the loop folds into an XOR network.
  function automatic logic [7:0] gf_mul(logic [7:0] x, logic [7:0] c);
    logic [7:0] r, a;
    r = 8'h00;
    a = x;
    for (int i = 0; i < 8; i++) begin
      if (c[i]) r = r ^ a;
      a = {a[6:0], 1'b0} ^ (a[7] ? 8'h2b : 8'h00);
    end
    return r;
  endfunction

  // One column times a matrix: y_r = sum_c M(r, c) x_c
  function automatic logic [31:0] col_mul4(logic [31:0] x, logic [127:0] m);
    logic [31:0] y;
    for (int r = 0; r < 4; r++) begin
      y[8*r +: 8] = 8'h00;
      for (int c = 0; c < 4; c++) begin
        y[8*r +: 8] = y[8*r +: 8] ^ gf_mul(x[8*c +: 8], m[8 * (15 - (4*r + c)) +: 8]);
      end
    end
    return y;
  endfunction

  function automatic logic [63:0] col_mul8(logic [63:0] x, logic [511:0] m);
    logic [63:0] y;
    for (int r = 0; r < 8; r++) begin
      y[8*r +: 8] = 8'h00;
      for (int c = 0; c < 8; c++) begin
        y[8*r +: 8] = y[8*r +: 8] ^ gf_mul(x[8*c +: 8], m[8 * (63 - (8*r + c)) +: 8]);
      end
    end
    return y;
  endfunction

  function automatic state_t sub_cells(state_t x);
    state_t y;
    for (int b = 0; b < 32; b++) y[8*b +: 8] = sbox(x[8*b +: 8]);
    return y;
  endfunction

  function automatic state_t inv_sub_cells(state_t x);
    state_t y;
    for (int b = 0; b < 32; b++) y[8*b +: 8] = sbox_inv(x[8*b +: 8]);
    return y;
  endfunction

  // Byte j of the result = byte (j + n) mod t of a column: the rotation
  // x <<<_w 8n of the standard, whose first (leftmost) byte is byte 0 here.
  // n is a constant in every use: wiring only.
  function automatic logic [31:0] rot4(logic [31:0] x, int unsigned n);
    logic [31:0] y;
    for (int unsigned j = 0; j < 4; j++) y[8*j +: 8] = x[8*((j + n) % 4) +: 8];
    return y;
  endfunction

  function automatic logic [63:0] rot8(logic [63:0] x, int unsigned n);
    logic [63:0] y;
    for (int unsigned j = 0; j < 8; j++) y[8*j +: 8] = x[8*((j + n) % 8) +: 8];
    return y;
  endfunction

  // y^c = M_t (x^c <<<_w c*w/4): column c is rotated by c bytes (MKV-128) or
  // 2c bytes (MKV-256) before the matrix (clause 5.4.3)
  function automatic state_t mix_words(state_t x, logic wide);
    state_t y8, y4;
    y4 = '0;
    for (int c = 0; c < 4; c++) begin
      y8[64*c +: 64] = col_mul8(rot8(x[64*c +: 64], 2 * c), M8);
      y4[32*c +: 32] = col_mul4(rot4(x[32*c +: 32], c), M4);
    end
    return wide ? y8 : y4;
  endfunction

  // y^c = (M_t^-1 x^c) >>>_w c*w/4 (clause 5.4.4)
  function automatic state_t inv_mix_words(state_t x, logic wide);
    state_t y8, y4;
    y4 = '0;
    for (int c = 0; c < 4; c++) begin
      y8[64*c +: 64] = rot8(col_mul8(x[64*c +: 64], M8Inv), 8 - 2 * c);
      y4[32*c +: 32] = rot4(col_mul4(x[32*c +: 32], M4Inv), 4 - c);
    end
    return wide ? y8 : y4;
  endfunction

  // y_c = XOR of the three other columns (an involution)
  function automatic state_t x_words(state_t x, logic wide);
    state_t      y8, y4;
    logic [63:0] t8;
    logic [31:0] t4;
    t8 = x[63:0] ^ x[127:64] ^ x[191:128] ^ x[255:192];
    t4 = x[31:0] ^ x[63:32] ^ x[95:64] ^ x[127:96];
    y4 = '0;
    for (int c = 0; c < 4; c++) begin
      y8[64*c +: 64] = t8 ^ x[64*c +: 64];
      y4[32*c +: 32] = t4 ^ x[32*c +: 32];
    end
    return wide ? y8 : y4;
  endfunction

  // Bits of the state used by a block size
  function automatic state_t block_mask(logic wide);
    return wide ? {256{1'b1}} : {128'h0, {128{1'b1}}};
  endfunction

  // Key schedule constant Const^0_l (left branch, K^0) or Const^1_l (right
  // branch, K^1) of clause 5.5, in the byte order of the state
  function automatic state_t ks_const(logic wide, logic left);
    if (wide) return left ? Const0L256 : Const1L256;
    return {128'h0, left ? Const0L128 : Const1L128};
  endfunction

endpackage
