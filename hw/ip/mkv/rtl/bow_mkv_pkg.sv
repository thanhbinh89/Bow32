// MKV block cipher (draft TCVN XXXX:2024): the layers of the round function
// on the 256 bit state of the Bow32 MKV core (docs/ip/mkv.md).
//
// Byte b of a block (in the order of the standard) is state[8*b +: 8]. The
// state has four sub-states (columns) of t bytes, column c = bytes
// c*t .. c*t+t-1, byte j of a column = entry j of the MixWords vector:
//   wide = 1  MKV-256, t = 8, columns state[64*c +: 64]
//   wide = 0  MKV-128, t = 4, columns state[32*c +: 32], bits 255:128 = 0
// The layer functions return 0 in bits 255:128 when wide = 0 (except
// sub_cells / inv_sub_cells, which work on every byte).

package bow_mkv_pkg;

  import bow_mkv_tables_pkg::*;

  typedef logic [255:0] state_t;

  // MixWords matrices M4, M4Inv, M8, M8Inv over GF(2^8) / x^8 + x^5 + x^3 + x + 1
  // come from bow_mkv_tables_pkg (generated by tools/mkv/mkv_model.py). M4
  // has 0x0D at (2, 3) and (3, 0), not the 0x0C printed in the draft: only
  // 0x0D gives the test vectors of Annex A and M4 * M4^-1 = I.

  // Product in GF(2^8); with a constant c the loop folds into an XOR network.
  function automatic logic [7:0] gf_mul(logic [7:0] x, logic [7:0] c);
    logic [7:0] r, a;
    r = 8'h00;
    a = x;
    for (int i = 0; i < 8; i++) begin
      if (c[i]) r = r ^ a;
      a = {a[6:0], 1'b0} ^ (a[7] ? 8'h2b : 8'h00);
    end
    return r;
  endfunction

  // One column times a matrix: y_r = sum_c M(r, c) x_c
  function automatic logic [31:0] col_mul4(logic [31:0] x, logic [127:0] m);
    logic [31:0] y;
    for (int r = 0; r < 4; r++) begin
      y[8*r +: 8] = 8'h00;
      for (int c = 0; c < 4; c++) begin
        y[8*r +: 8] = y[8*r +: 8] ^ gf_mul(x[8*c +: 8], m[8 * (15 - (4*r + c)) +: 8]);
      end
    end
    return y;
  endfunction

  function automatic logic [63:0] col_mul8(logic [63:0] x, logic [511:0] m);
    logic [63:0] y;
    for (int r = 0; r < 8; r++) begin
      y[8*r +: 8] = 8'h00;
      for (int c = 0; c < 8; c++) begin
        y[8*r +: 8] = y[8*r +: 8] ^ gf_mul(x[8*c +: 8], m[8 * (63 - (8*r + c)) +: 8]);
      end
    end
    return y;
  endfunction

  function automatic state_t sub_cells(state_t x);
    state_t y;
    for (int b = 0; b < 32; b++) y[8*b +: 8] = sbox(x[8*b +: 8]);
    return y;
  endfunction

  function automatic state_t inv_sub_cells(state_t x);
    state_t y;
    for (int b = 0; b < 32; b++) y[8*b +: 8] = sbox_inv(x[8*b +: 8]);
    return y;
  endfunction

  function automatic state_t mix_words(state_t x, logic wide);
    state_t y8, y4;
    y4 = '0;
    for (int c = 0; c < 4; c++) begin
      y8[64*c +: 64] = col_mul8(x[64*c +: 64], M8);
      y4[32*c +: 32] = col_mul4(x[32*c +: 32], M4);
    end
    return wide ? y8 : y4;
  endfunction

  function automatic state_t inv_mix_words(state_t x, logic wide);
    state_t y8, y4;
    y4 = '0;
    for (int c = 0; c < 4; c++) begin
      y8[64*c +: 64] = col_mul8(x[64*c +: 64], M8Inv);
      y4[32*c +: 32] = col_mul4(x[32*c +: 32], M4Inv);
    end
    return wide ? y8 : y4;
  endfunction

  // y_c = XOR of the three other columns (an involution)
  function automatic state_t x_words(state_t x, logic wide);
    state_t      y8, y4;
    logic [63:0] t8;
    logic [31:0] t4;
    t8 = x[63:0] ^ x[127:64] ^ x[191:128] ^ x[255:192];
    t4 = x[31:0] ^ x[63:32] ^ x[95:64] ^ x[127:96];
    y4 = '0;
    for (int c = 0; c < 4; c++) begin
      y8[64*c +: 64] = t8 ^ x[64*c +: 64];
      y4[32*c +: 32] = t4 ^ x[32*c +: 32];
    end
    return wide ? y8 : y4;
  endfunction

  // Bits of the state used by a block size
  function automatic state_t block_mask(logic wide);
    return wide ? {256{1'b1}} : {128'h0, {128{1'b1}}};
  endfunction

endpackage
