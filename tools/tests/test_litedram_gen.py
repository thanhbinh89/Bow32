"""Unit tests for the parts of hw/ip/ddr/litedram/bow_ddr_litedram_gen.py that
run without LiteX: strip_dates, which makes the generated cores byte-identical
whatever LiteX reports as its revision (`make litedram-check`).
Run: python3 -m unittest discover tools/tests
"""

import importlib.util
import unittest
from pathlib import Path

GEN = Path(__file__).resolve().parents[2] / "hw" / "ip" / "ddr" / "litedram" / "bow_ddr_litedram_gen.py"

try:
    import yaml  # noqa: F401  (imported by the generator)
except ImportError:
    yaml = None


def load_generator():
    spec = importlib.util.spec_from_file_location("bow_ddr_litedram_gen", GEN)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


@unittest.skipIf(yaml is None, "PyYAML is not installed")
class StripDatesTest(unittest.TestCase):
    def setUp(self):
        self.gen = load_generator()

    def strip(self, text):
        return self.gen.strip_dates(text)

    def test_revisions(self):
        # git rev-parse in the LiteX package directory: a hash, a dirty tree,
        # or '--------' when git is missing or the venv is outside a work tree
        for rev in ("c12fae344", "c12fae344-dirty", "--------", ""):
            with self.subTest(rev=rev):
                self.assertEqual(self.strip(f"// Auto-generated by LiteX ({rev}) on 2026-11-05 10:11:12\n"),
                                 "// Auto-generated by LiteX\n")
                self.assertEqual(self.strip(f"# Auto-generated by LiteX ({rev}) on 2026-11-05 10:11:12\n"),
                                 "# Auto-generated by LiteX\n")

    def test_header_lines(self):
        text = ("// Date      : 2026-11-05 10:11:12\n"
                "// LiteX sha1 : c12fae344\n"
                "`timescale 1ns / 1ps\n"
                "module litedram_ddr2 (\n")
        self.assertEqual(self.strip(text), "module litedram_ddr2 (\n")

    def test_other_text_kept(self):
        text = "assign x = (a) ? b : c; // LiteX core (DDR2)\n"
        self.assertEqual(self.strip(text), text)


if __name__ == "__main__":
    unittest.main()
