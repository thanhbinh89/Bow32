"""Generate SoC memory map artefacts from hw/top/data/bow32_memmap.yaml.

Outputs (paths relative to the repository root):
  hw/top/rtl/bow32_memmap_pkg.sv
  sw/common/include/bow32_memmap.h
  sw/common/link/bow32_memory.ld
  docs/memory_map.md

Usage:
  tools/gen_memmap.py           # (re)write all outputs
  tools/gen_memmap.py --check   # exit 1 if any output is stale (used by CI)
"""

import argparse
import sys
from pathlib import Path

try:
    import yaml
except ImportError:  # pragma: no cover
    sys.exit("error: PyYAML is required (pip install -r requirements.txt)")

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "hw/top/data/bow32_memmap.yaml"

OUT_SV = ROOT / "hw/top/rtl/bow32_memmap_pkg.sv"
OUT_H = ROOT / "sw/common/include/bow32_memmap.h"
OUT_LD = ROOT / "sw/common/link/bow32_memory.ld"
OUT_MD = ROOT / "docs/memory_map.md"

BANNER = "AUTO-GENERATED by tools/gen_memmap.py from hw/top/data/bow32_memmap.yaml - DO NOT EDIT"


def camel(name):
    return "".join(p.capitalize() for p in name.split("_"))


def human_size(size):
    if size >= 1024 and size % 1024 == 0:
        return f"{size // 1024} KiB"
    return f"{size} B"


def validate(mm):
    errors = []
    for bus in ("main_bus", "periph_bus"):
        regions = mm[bus]
        names = set()
        for r in regions:
            base, size = r["base"], r["size"]
            if r["name"] in names:
                errors.append(f"{bus}: duplicate name '{r['name']}'")
            names.add(r["name"])
            if size == 0 or size & (size - 1):
                errors.append(f"{bus}.{r['name']}: size 0x{size:x} is not a power of two")
            if base % size:
                errors.append(f"{bus}.{r['name']}: base 0x{base:08x} not aligned to size")
        ordered = sorted(regions, key=lambda r: r["base"])
        for a, b in zip(ordered, ordered[1:]):
            if a["base"] + a["size"] > b["base"]:
                errors.append(f"{bus}: '{a['name']}' overlaps '{b['name']}'")
    periph = next(r for r in mm["main_bus"] if r["name"] == "periph")
    for r in mm["periph_bus"]:
        if not (periph["base"] <= r["base"] and
                r["base"] + r["size"] <= periph["base"] + periph["size"]):
            errors.append(f"periph_bus.{r['name']}: outside the 'periph' window")
    lines = [i["line"] for i in mm["irq_fast"]]
    if len(lines) != len(set(lines)) or any(not 0 <= l < 15 for l in lines):
        errors.append("irq_fast: lines must be unique and in [0, 14]")
    if errors:
        sys.exit("memory map errors:\n  " + "\n  ".join(errors))


def gen_sv(mm):
    o = [f"// {BANNER}", "//", "// SoC address map constants. Device indices are the port numbers of the",
         "// corresponding bow_bus_xbar instance in bow32_top.", "",
         "package bow32_memmap_pkg;", "",
         f"  localparam logic [31:0] ChipId   = 32'h{mm['soc']['chip_id']:08X};",
         f"  localparam logic [31:0] BootAddr = 32'h{mm['soc']['boot_addr']:08X};", ""]
    for bus, prefix in (("main_bus", "Main"), ("periph_bus", "Periph")):
        regions = mm[bus]
        n = len(regions)
        o.append(f"  // {bus}")
        o.append(f"  localparam int unsigned {prefix}NumDevices = {n};")
        for i, r in enumerate(regions):
            o.append(f"  localparam int unsigned {prefix}Dev{camel(r['name'])} = {i};")
        for r in regions:
            c = camel(r["name"])
            o.append(f"  localparam logic [31:0] {c}Base = 32'h{r['base']:08X};")
            o.append(f"  localparam logic [31:0] {c}Size = 32'h{r['size']:08X};")
        # Packed arrays: element [i] corresponds to device index i.
        bases = ", ".join(f"{camel(r['name'])}Base" for r in reversed(regions))
        masks = ", ".join(f"~({camel(r['name'])}Size - 32'd1)" for r in reversed(regions))
        o.append(f"  localparam logic [{prefix}NumDevices-1:0][31:0] {prefix}DevBase = {{{bases}}};")
        o.append(f"  localparam logic [{prefix}NumDevices-1:0][31:0] {prefix}DevMask = {{{masks}}};")
        o.append("")
    o.append("  // Ibex fast interrupt lines")
    for irq in mm["irq_fast"]:
        o.append(f"  localparam int unsigned IrqFast{camel(irq['name'])} = {irq['line']};")
    o += ["", "endpackage", ""]
    return "\n".join(o)


def gen_h(mm):
    o = [f"/* {BANNER} */", "", "#ifndef BOW32_MEMMAP_H_", "#define BOW32_MEMMAP_H_", "",
         f"#define BOW32_CHIP_ID   0x{mm['soc']['chip_id']:08X}u",
         f"#define BOW32_BOOT_ADDR 0x{mm['soc']['boot_addr']:08X}u", ""]
    for bus in ("main_bus", "periph_bus"):
        o.append(f"/* {bus} */")
        for r in mm[bus]:
            n = r["name"].upper()
            o.append(f"#define BOW32_{n}_BASE 0x{r['base']:08X}u")
            o.append(f"#define BOW32_{n}_SIZE 0x{r['size']:08X}u")
        o.append("")
    o.append("/* Ibex fast interrupt lines (mcause = 0x80000000 | (16 + line)) */")
    for irq in mm["irq_fast"]:
        o.append(f"#define BOW32_IRQ_FAST_{irq['name'].upper()} {irq['line']}")
    o += ["", "#endif /* BOW32_MEMMAP_H_ */", ""]
    return "\n".join(o)


def gen_ld(mm):
    o = [f"/* {BANNER} */", "", "MEMORY", "{"]
    attrs = {"rom": "rx", "flash": "rx", "sram": "rwx"}
    for r in mm["main_bus"]:
        if r["name"] in attrs:
            o.append(f"  {r['name'].upper():<6} ({attrs[r['name']]}) : ORIGIN = 0x{r['base']:08X}, "
                     f"LENGTH = 0x{r['size']:08X}")
    o += ["}", ""]
    return "\n".join(o)


def gen_md(mm):
    o = [f"<!-- {BANNER} -->", "", "# Bản đồ bộ nhớ (Memory map)", "",
         "Tệp này được sinh tự động từ `hw/top/data/bow32_memmap.yaml`. "
         "Sửa YAML rồi chạy `make gen`.", "",
         f"- Chip ID: `0x{mm['soc']['chip_id']:08X}`",
         f"- Boot address (`boot_addr_i`): `0x{mm['soc']['boot_addr']:08X}` "
         f"(PC sau reset = `0x{mm['soc']['boot_addr'] + 0x80:08X}`)", ""]
    for bus, title in (("main_bus", "Main bus (crossbar)"), ("periph_bus", "Peripheral bus")):
        o += [f"## {title}", "", "| Port | Tên | Base | End | Size | Mô tả |",
              "|-----:|-----|------|-----|------|-------|"]
        for i, r in enumerate(mm[bus]):
            end = r["base"] + r["size"] - 1
            o.append(f"| {i} | `{r['name']}` | `0x{r['base']:08X}` | `0x{end:08X}` | "
                     f"{human_size(r['size'])} | {r['desc']} |")
        o.append("")
    o += ["Truy cập vào địa chỉ không được ánh xạ trả về bus error "
          "(Ibex sinh exception *load/store/instruction access fault*).", "",
          "## Ngắt nhanh (Ibex `irq_fast_i`)", "", "| Line | mcause | Nguồn | Mô tả |",
          "|-----:|-------:|-------|-------|"]
    for irq in mm["irq_fast"]:
        o.append(f"| {irq['line']} | `0x{0x80000000 | (16 + irq['line']):08X}` | "
                 f"`{irq['name']}` | {irq['desc']} |")
    o.append("")
    return "\n".join(o)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--check", action="store_true", help="only check that outputs are up to date")
    args = ap.parse_args()

    mm = yaml.safe_load(SRC.read_text())
    validate(mm)
    outputs = {OUT_SV: gen_sv(mm), OUT_H: gen_h(mm), OUT_LD: gen_ld(mm), OUT_MD: gen_md(mm)}

    stale = []
    for path, text in outputs.items():
        if path.exists() and path.read_text() == text:
            continue
        stale.append(path.relative_to(ROOT))
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if args.check:
        if stale:
            print("stale generated files (run `make gen`):", *stale, sep="\n  ")
            return 1
        print("memory map outputs are up to date")
    else:
        for p in stale:
            print(f"wrote {p}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
